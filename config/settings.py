# Database
# https://docs.djangoproject.com/en/5.2/ref/settings/#databases

_database_url = os.environ.get('DATABASE_URL', '').strip()
if _database_url:
    import dj_database_url

    _production_database = dj_database_url.parse(
        _database_url,
        conn_max_age=int(os.environ.get('DJANGO_DB_CONN_MAX_AGE', '60')),
        conn_health_checks=True,
    )
    if _production_database['ENGINE'] == 'django.db.backends.postgresql':
        # Bound connection setup so startup/readiness does not wait indefinitely
        # for an unreachable database. The timeout is per libpq connection host.
        _connection_options = _production_database.setdefault('OPTIONS', {})
        _raw_connect_timeout = os.environ.get('DJANGO_DB_CONNECT_TIMEOUT',
            _connection_options.get('connect_timeout', 5))
        try:
            _database_connect_timeout = int(_raw_connect_timeout)
        except (TypeError, ValueError):
            raise ImproperlyConfigured('PostgreSQL connect timeout must be an integer between 1 and 30 seconds.') from None
        if not 1 <= _database_connect_timeout <= 30:
            raise ImproperlyConfigured('PostgreSQL connect timeout must be an integer between 1 and 30 seconds.')
        _connection_options['connect_timeout'] = _database_connect_timeout
    if not DEBUG and _production_database['ENGINE'] != 'django.db.backends.postgresql':
        raise ImproperlyConfigured(
            'Production DATABASE_URL must use PostgreSQL; SQLite and other database backends are not supported.'
        )
    DATABASES = {
        'default': _production_database,
    }
elif DEBUG:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    }
else:
    raise ImproperlyConfigured(
        'DATABASE_URL is required in production; SQLite is supported for local development only.'
    )


